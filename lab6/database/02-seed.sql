-- Слоты на следующие 14 дней, по три времени UTC для каждого специалиста.
-- Повторный запуск добавляет даты в конец расписания. Существующие записи сохраняются.
INSERT INTO consultation_slots (id, specialist_id, starts_at)
SELECT s.id || '-' || to_char(t.starts_at AT TIME ZONE 'UTC', 'YYYYMMDDHH'), s.id, t.starts_at
FROM specialists AS s
CROSS JOIN generate_series(1, 14) AS d(day_offset)
CROSS JOIN (VALUES (9), (13), (16)) AS h(hour_utc)
CROSS JOIN LATERAL (
    SELECT (date_trunc('day', now() AT TIME ZONE 'UTC') +
            make_interval(days => d.day_offset, hours => h.hour_utc)) AT TIME ZONE 'UTC' AS starts_at
) AS t
ON CONFLICT (specialist_id, starts_at) DO NOTHING;

